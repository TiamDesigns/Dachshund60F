#!/usr/bin/env python3
"""Generate the config protocol bindings from protocol/protocol.yaml.

    python protocol/gen/gen.py          # write the generated files
    python protocol/gen/gen.py --check  # fail if any is out of date (CI)

Writes firmware/core/include/kb/protocol_gen.h, firmware/core/src/protocol_gen.c
and host-lib/src/protocol.gen.ts. Also host-lib/src/keycodes.gen.ts: the
keycode numbers from firmware/core/include/kb/keycodes.h, which the protocol
carries. Needs PyYAML, which every NCS install has.
"""

import argparse
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
SPEC = REPO / "protocol" / "protocol.yaml"
OUT_H = REPO / "firmware" / "core" / "include" / "kb" / "protocol_gen.h"
OUT_C = REPO / "firmware" / "core" / "src" / "protocol_gen.c"
OUT_TS = REPO / "host-lib" / "src" / "protocol.gen.ts"
KEYCODES_H = REPO / "firmware" / "core" / "include" / "kb" / "keycodes.h"
OUT_KC_TS = REPO / "host-lib" / "src" / "keycodes.gen.ts"

BANNER = "Generated by protocol/gen/gen.py from protocol/protocol.yaml. Do not edit."

SCALARS = {"u8": 1, "u16": 2, "u32": 4}


class Field:
    def __init__(self, raw, where):
        self.name = raw["name"]
        self.doc = raw.get("doc")
        t = raw["type"]
        if not re.fullmatch(r"[a-z][a-z0-9_]*", self.name):
            raise SystemExit(f"{where}: bad field name {self.name!r}")
        self.kind = None
        if t in SCALARS:
            self.kind, self.size = "scalar", SCALARS[t]
            self.type = t
        elif m := re.fullmatch(r"char\[(\d+)\]", t):
            self.kind, self.size = "char", int(m[1])
        elif t in ("u8[]", "u16[]"):
            self.kind, self.max = "array", int(raw["max"])
            self.elem = 1 if t == "u8[]" else 2
            self.size = 0
        else:
            raise SystemExit(f"{where}: unknown type {t!r}")


class Message:
    def __init__(self, cmd, direction, raw, max_payload):
        self.cmd = cmd
        self.direction = direction  # "req" or "resp"
        where = f"{cmd['name']}.{'request' if direction == 'req' else 'response'}"
        self.fields = [Field(f, where) for f in raw]
        for f in self.fields[:-1]:
            if f.kind == "array":
                raise SystemExit(f"{where}: an array must be the last field")
        self.fixed = sum(f.size for f in self.fields)
        self.array = self.fields[-1] if self.fields and self.fields[-1].kind == "array" else None
        self.max_size = self.fixed + (self.array.elem * self.array.max if self.array else 0)
        if self.max_size > max_payload:
            raise SystemExit(f"{where}: {self.max_size} bytes exceeds the {max_payload}-byte payload")

    @property
    def c_name(self):
        return f"kb_proto_{self.cmd['name']}_{self.direction}"

    @property
    def ts_name(self):
        return camel(self.cmd["name"], upper=True) + ("Request" if self.direction == "req" else "Response")


def camel(name, upper=False):
    parts = name.split("_")
    s = parts[0] + "".join(p.capitalize() for p in parts[1:])
    return s[0].upper() + s[1:] if upper else s


def load():
    spec = yaml.safe_load(SPEC.read_text(encoding="utf-8"))
    max_payload = spec["frame"]["max_payload"]
    if spec["frame"]["header_size"] + max_payload != spec["hid"]["report_size"]:
        raise SystemExit("frame: header_size + max_payload must equal hid.report_size")

    allowed = {"errors": {"name", "code", "doc"}, "capabilities": {"name", "bit", "doc"},
               "feature_tables": {"name", "id", "size", "entries", "doc"},
               "commands": {"name", "id", "doc", "request", "response"}}
    for key, keys in allowed.items():
        for item in spec[key]:
            # A comma in an unquoted flow-style doc splits it into extra keys.
            if set(item) - keys:
                raise SystemExit(f"{key}: {item.get('name')}: unexpected {sorted(set(item) - keys)}; quote docs with commas")
    for cmd in spec["commands"]:
        for f in cmd["request"] + cmd["response"]:
            if set(f) - {"name", "type", "doc", "max"}:
                raise SystemExit(f"{cmd['name']}: field {f.get('name')}: unexpected {sorted(set(f) - {'name', 'type', 'doc', 'max'})}")

    for key, field in (("errors", "code"), ("commands", "id"), ("capabilities", "bit"), ("feature_tables", "id")):
        seen_names, seen_values = set(), set()
        for item in spec[key]:
            if item["name"] in seen_names or item[field] in seen_values:
                raise SystemExit(f"{key}: duplicate {item['name']} or {field} {item[field]}")
            seen_names.add(item["name"])
            seen_values.add(item[field])
    if any(not 0 < c["id"] < 0xFF for c in spec["commands"]):
        raise SystemExit("commands: ids must be 0x01-0xFE")
    if any(not 0 < t["size"] <= max_payload - 4 for t in spec["feature_tables"]):
        raise SystemExit("feature_tables: size must fit a get_feature response")
    if any(not 0 <= c["bit"] < 32 for c in spec["capabilities"]):
        raise SystemExit("capabilities: bits must be 0-31")

    messages = []
    for cmd in spec["commands"]:
        messages.append(Message(cmd, "req", cmd["request"], max_payload))
        messages.append(Message(cmd, "resp", cmd["response"], max_payload))
    return spec, messages


# C


def c_fields(m):
    lines = []
    for f in m.fields:
        if f.kind == "scalar":
            lines.append(f"    uint{f.size * 8}_t {f.name};")
        elif f.kind == "char":
            lines.append(f"    char {f.name}[{f.size + 1}]; /* NUL-terminated */")
        else:
            lines.append(f"    uint8_t {f.name}_count;")
            lines.append(f"    uint{f.elem * 8}_t {f.name}[{f.max}];")
    return lines


def gen_h(spec, messages):
    o = [f"/* {BANNER} */", "#ifndef KB_PROTOCOL_GEN_H", "#define KB_PROTOCOL_GEN_H", ""]
    o += ["#include <stddef.h>", "#include <stdint.h>", ""]
    hid, frame = spec["hid"], spec["frame"]
    o += [
        f"#define KB_PROTO_VERSION {spec['version']}u",
        f"#define KB_PROTO_HID_USAGE_PAGE 0x{hid['usage_page']:04X}u",
        f"#define KB_PROTO_HID_USAGE 0x{hid['usage']:02X}u",
        f"#define KB_PROTO_REPORT_SIZE {hid['report_size']}u",
        f"#define KB_PROTO_HID_BLE_REPORT_ID {hid['ble_report_id']}u",
        f"#define KB_PROTO_HEADER_SIZE {frame['header_size']}u",
        f"#define KB_PROTO_MAX_PAYLOAD {frame['max_payload']}u",
        "",
        "/* Header byte offsets */",
        "#define KB_PROTO_OFF_COMMAND 0u",
        "#define KB_PROTO_OFF_SEQUENCE 1u",
        "#define KB_PROTO_OFF_LENGTH 2u",
        "#define KB_PROTO_OFF_VERSION 3u /* request */",
        "#define KB_PROTO_OFF_STATUS 3u  /* response */",
        "",
        "enum kb_proto_status {",
    ]
    o += [f"    KB_PROTO_{e['name'].upper()} = {e['code']}, /* {e['doc']} */" for e in spec["errors"]]
    o += ["};", "", "enum kb_proto_command {"]
    o += [f"    KB_PROTO_CMD_{c['name'].upper()} = 0x{c['id']:02X}," for c in spec["commands"]]
    o += ["};", "", "/* Handshake capability bits */"]
    o += [f"#define KB_PROTO_CAP_{c['name'].upper()} (1u << {c['bit']}) /* {c['doc']} */" for c in spec["capabilities"]]
    o += ["", "/* Advanced-key tables: id, entry size in bytes and entry count */"]
    for t in spec["feature_tables"]:
        n = t["name"].upper()
        o += [f"#define KB_PROTO_TABLE_{n} {t['id']}u", f"#define KB_PROTO_TABLE_{n}_SIZE {t['size']}u",
              f"#define KB_PROTO_TABLE_{n}_ENTRIES {t['entries']}u"]
    o.append(f"#define KB_PROTO_TABLE_COUNT {len(spec['feature_tables'])}u")
    o.append("")

    for m in messages:
        if not m.fields:
            continue
        o.append(f"/* {m.cmd['name']} {'request' if m.direction == 'req' else 'response'} */")
        size_name = f"{m.c_name.upper()}_{'MIN_SIZE' if m.array else 'SIZE'}"
        o.append(f"#define {size_name} {m.fixed}u")
        if m.array:
            o.append(f"#define {m.c_name.upper()}_MAX_{m.array.name.upper()} {m.array.max}u")
        o.append(f"struct {m.c_name} {{")
        o += c_fields(m)
        o.append("};")
        o.append(f"/* Returns 0, or -1 if len is wrong for this message. */")
        o.append(f"int {m.c_name}_decode(const uint8_t *p, size_t len, struct {m.c_name} *out);")
        o.append(f"/* Writes the payload into p (KB_PROTO_MAX_PAYLOAD bytes) and returns its length. */")
        o.append(f"size_t {m.c_name}_encode(const struct {m.c_name} *in, uint8_t *p);")
        o.append("")
    o += ["#endif /* KB_PROTOCOL_GEN_H */", ""]
    return "\n".join(o)


def gen_c(spec, messages):
    o = [f"/* {BANNER} */", '#include "kb/protocol_gen.h"', "", "#include <string.h>", ""]
    o += [
        "static uint16_t get16(const uint8_t *p) { return (uint16_t)(p[0] | (p[1] << 8)); }",
        "static uint32_t get32(const uint8_t *p)",
        "{",
        "    return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);",
        "}",
        "static void put16(uint8_t *p, uint16_t v)",
        "{",
        "    p[0] = (uint8_t)v;",
        "    p[1] = (uint8_t)(v >> 8);",
        "}",
        "static void put32(uint8_t *p, uint32_t v)",
        "{",
        "    put16(p, (uint16_t)v);",
        "    put16(p + 2, (uint16_t)(v >> 16));",
        "}",
        "static size_t text_len(const char *s, size_t max)",
        "{",
        "    size_t n = 0;",
        "    while (n < max && s[n] != '\\0') {",
        "        n++;",
        "    }",
        "    return n;",
        "}",
        "",
    ]
    used = {"get16": False, "get32": False, "put16": False, "put32": False, "text_len": False}
    body = []
    for m in messages:
        if not m.fields:
            continue
        # decode
        body.append(f"int {m.c_name}_decode(const uint8_t *p, size_t len, struct {m.c_name} *out)")
        body.append("{")
        if m.array and m.array.elem == 1:
            body.append(f"    if (len < {m.fixed}u || len - {m.fixed}u > {m.array.max}u) {{")
        elif m.array:
            body.append(f"    if (len < {m.fixed}u || (len - {m.fixed}u) % 2u != 0 || (len - {m.fixed}u) / 2u > {m.array.max}u) {{")
        else:
            body.append(f"    if (len != {m.fixed}u) {{")
        body += ["        return -1;", "    }", "    memset(out, 0, sizeof(*out));"]
        off = 0
        for f in m.fields:
            if f.kind == "scalar":
                if f.size == 1:
                    body.append(f"    out->{f.name} = p[{off}];")
                else:
                    used[f"get{f.size * 8}"] = True
                    body.append(f"    out->{f.name} = get{f.size * 8}(p + {off});")
                off += f.size
            elif f.kind == "char":
                body.append(f"    memcpy(out->{f.name}, p + {off}, {f.size});")
                off += f.size
            elif f.elem == 1:
                body.append(f"    out->{f.name}_count = (uint8_t)(len - {off}u);")
                body.append(f"    memcpy(out->{f.name}, p + {off}, out->{f.name}_count);")
            else:
                used["get16"] = True
                body.append(f"    out->{f.name}_count = (uint8_t)((len - {off}u) / 2u);")
                body.append(f"    for (size_t i = 0; i < out->{f.name}_count; i++) {{")
                body.append(f"        out->{f.name}[i] = get16(p + {off} + 2u * i);")
                body.append("    }")
        if not any(f.kind == "array" for f in m.fields):
            pass
        body += ["    return 0;", "}", ""]
        # encode
        body.append(f"size_t {m.c_name}_encode(const struct {m.c_name} *in, uint8_t *p)")
        body.append("{")
        off = 0
        for f in m.fields:
            if f.kind == "scalar":
                if f.size == 1:
                    body.append(f"    p[{off}] = in->{f.name};")
                else:
                    used[f"put{f.size * 8}"] = True
                    body.append(f"    put{f.size * 8}(p + {off}, in->{f.name});")
                off += f.size
            elif f.kind == "char":
                body.append(f"    memset(p + {off}, 0, {f.size});")
                used["text_len"] = True
                body.append(f"    memcpy(p + {off}, in->{f.name}, text_len(in->{f.name}, {f.size}));")
                off += f.size
            elif f.elem == 1:
                body.append(f"    size_t n = in->{f.name}_count < {f.max}u ? in->{f.name}_count : {f.max}u;")
                body.append(f"    memcpy(p + {off}, in->{f.name}, n);")
                body.append(f"    return {off}u + n;")
            else:
                used["put16"] = True
                body.append(f"    size_t n = in->{f.name}_count < {f.max}u ? in->{f.name}_count : {f.max}u;")
                body.append("    for (size_t i = 0; i < n; i++) {")
                body.append(f"        put16(p + {off} + 2u * i, in->{f.name}[i]);")
                body.append("    }")
                body.append(f"    return {off}u + 2u * n;")
        if not m.array:
            body.append(f"    return {m.fixed}u;")
        body += ["}", ""]
    # Drop helpers nothing uses (they'd warn as unused statics).
    helpers = "\n".join(o[5:])
    for name, is_used in used.items():
        if not is_used:
            helpers = remove_function(helpers, name)
    out = "\n".join(o[:5]) + "\n" + helpers.rstrip("\n") + "\n\n" + "\n".join(body)
    return out.rstrip("\n") + "\n"


def remove_function(text, name):
    lines = text.split("\n")
    out, skip = [], False
    for line in lines:
        if re.match(rf"static \w+ {name}\(", line):
            skip = not line.rstrip().endswith("}")
            continue
        if skip:
            if line == "}":
                skip = False
            continue
        out.append(line)
    return "\n".join(out)


# TypeScript


def ts_type(f):
    if f.kind == "scalar":
        return "number"
    if f.kind == "char":
        return "string"
    return "Uint8Array" if f.elem == 1 else "number[]"


def gen_ts(spec, messages):
    o = [f"// {BANNER}", ""]
    hid, frame = spec["hid"], spec["frame"]
    o += [
        f"export const PROTOCOL_VERSION = {spec['version']};",
        f"export const HID_USAGE_PAGE = 0x{hid['usage_page']:04x};",
        f"export const HID_USAGE = 0x{hid['usage']:02x};",
        f"export const REPORT_SIZE = {hid['report_size']};",
        f"export const HID_BLE_REPORT_ID = {hid['ble_report_id']};",
        f"export const HEADER_SIZE = {frame['header_size']};",
        f"export const MAX_PAYLOAD = {frame['max_payload']};",
        "",
        "export const Status = {",
    ]
    o += [f"  {camel(e['name'])}: {e['code']}," for e in spec["errors"]]
    o += ["} as const;", "export type StatusName = keyof typeof Status;", ""]
    o += ["/** What each status code means, by code. */", "export const STATUS_TEXT: Record<number, string> = {"]
    o += [f"  {e['code']}: {e['doc']!r}," for e in spec["errors"]]
    o += ["};", "", "export const Command = {"]
    o += [f"  {camel(c['name'])}: 0x{c['id']:02x}," for c in spec["commands"]]
    o += ["} as const;", "export type CommandName = keyof typeof Command;", "", "export const Capability = {"]
    o += [f"  {camel(c['name'])}: 1 << {c['bit']}," for c in spec["capabilities"]]
    o += ["} as const;", ""]
    o += ["/** Advanced-key tables: id, entry size in bytes and most entries (see protocol.yaml). */"]
    o += ["export const FeatureTable = {"]
    o += [f"  {camel(t['name'])}: {{ id: {t['id']}, size: {t['size']}, entries: {t['entries']} }}," for t in spec["feature_tables"]]
    o += ["} as const;", "export type FeatureTableName = keyof typeof FeatureTable;", ""]
    o += [
        "/** A payload that doesn't fit its message. */",
        "export class PayloadError extends Error {}",
        "",
        "const enc = new TextEncoder();",
        "const dec = new TextDecoder();",
        "",
        "function u8(v: number, name: string): number {",
        "  if (!Number.isInteger(v) || v < 0 || v > 0xff) throw new PayloadError(`${name} must be 0-255`);",
        "  return v;",
        "}",
        "",
        "function u16(v: number, name: string): number {",
        "  if (!Number.isInteger(v) || v < 0 || v > 0xffff) throw new PayloadError(`${name} must be 0-65535`);",
        "  return v;",
        "}",
        "",
        "function u32(v: number, name: string): number {",
        "  if (!Number.isInteger(v) || v < 0 || v > 0xffffffff) throw new PayloadError(`${name} must be 0-4294967295`);",
        "  return v;",
        "}",
        "",
        "function text(p: Uint8Array, off: number, size: number): string {",
        "  const bytes = p.subarray(off, off + size);",
        "  const end = bytes.indexOf(0);",
        "  return dec.decode(end < 0 ? bytes : bytes.subarray(0, end));",
        "}",
        "",
    ]
    for m in messages:
        cmdname = camel(m.cmd["name"], upper=True)
        dirname = "Request" if m.direction == "req" else "Response"
        if m.cmd.get("doc") and m.direction == "req":
            o.append(f"/** {m.cmd['doc']} */")
        if m.fields:
            o.append(f"export interface {m.ts_name} {{")
            for f in m.fields:
                doc = f" /** {f.doc} */" if f.doc else ""
                o.append(f"  {camel(f.name)}: {ts_type(f)};{doc}")
            o.append("}")
        else:
            o.append(f"export type {m.ts_name} = Record<string, never>;")
        o.append("")
        # encode
        arg = "m" if m.fields else "_m"
        o.append(f"export function encode{cmdname}{dirname}({arg}: {m.ts_name}): Uint8Array {{")
        if m.array:
            a = camel(m.array.name)
            o.append(f"  if (m.{a}.length > {m.array.max}) throw new PayloadError(\"{m.array.name}: at most {m.array.max}\");")
            o.append(f"  const p = new Uint8Array({m.fixed} + {m.array.elem} * m.{a}.length);")
        else:
            o.append(f"  const p = new Uint8Array({m.fixed});")
        if m.fields:
            o.append("  const v = new DataView(p.buffer);")
        off = 0
        for f in m.fields:
            n = camel(f.name)
            if f.kind == "scalar":
                setter = {1: "setUint8", 2: "setUint16", 4: "setUint32"}[f.size]
                check = {1: "u8", 2: "u16", 4: "u32"}[f.size]
                le = "" if f.size == 1 else ", true"
                o.append(f"  v.{setter}({off}, {check}(m.{n}, \"{f.name}\"){le});")
                off += f.size
            elif f.kind == "char":
                o.append(f"  const {n}Bytes = enc.encode(m.{n});")
                o.append(f"  if ({n}Bytes.length > {f.size}) throw new PayloadError(\"{f.name}: at most {f.size} bytes\");")
                o.append(f"  p.set({n}Bytes, {off});")
                off += f.size
            elif f.elem == 1:
                o.append(f"  p.set(m.{n}, {off});")
            else:
                o.append(f"  m.{n}.forEach((x, i) => v.setUint16({off} + 2 * i, u16(x, \"{f.name}\"), true));")
        o += ["  return p;", "}", ""]
        # decode
        parg = "p" if m.fields else "p"
        o.append(f"export function decode{cmdname}{dirname}({parg}: Uint8Array): {m.ts_name} {{")
        if m.array and m.array.elem == 1:
            o.append(f"  if (p.length < {m.fixed} || p.length - {m.fixed} > {m.array.max}) {{")
        elif m.array:
            o.append(
                f"  if (p.length < {m.fixed} || (p.length - {m.fixed}) % 2 !== 0 || (p.length - {m.fixed}) / 2 > {m.array.max}) {{"
            )
        else:
            o.append(f"  if (p.length !== {m.fixed}) {{")
        o.append(f"    throw new PayloadError(`{m.cmd['name']} {dirname.lower()}: bad length ${{p.length}}`);")
        o.append("  }")
        if not m.fields:
            o += ["  return {};", "}", ""]
            continue
        o.append("  const v = new DataView(p.buffer, p.byteOffset, p.byteLength);")
        o.append("  return {")
        off = 0
        for f in m.fields:
            n = camel(f.name)
            if f.kind == "scalar":
                getter = {1: "getUint8", 2: "getUint16", 4: "getUint32"}[f.size]
                le = "" if f.size == 1 else ", true"
                o.append(f"    {n}: v.{getter}({off}{le}),")
                off += f.size
            elif f.kind == "char":
                o.append(f"    {n}: text(p, {off}, {f.size}),")
                off += f.size
            elif f.elem == 1:
                o.append(f"    {n}: p.slice({off}),")
            else:
                o.append(f"    {n}: Array.from({{ length: (p.length - {off}) / 2 }}, (_, i) => v.getUint16({off} + 2 * i, true)),")
        o += ["  };", "}", ""]
    return "\n".join(o).rstrip("\n") + "\n"


# Keycodes


def keycode_constants():
    """Every object-like #define in keycodes.h that evaluates to a number."""
    text = re.sub(r"/\*.*?\*/", "", KEYCODES_H.read_text(encoding="utf-8"), flags=re.S)
    values = {}
    for m in re.finditer(r"^#define\s+(\w+)[ \t]+(.+)$", text, flags=re.M):
        name, expr = m[1], m[2].strip()
        expr = re.sub(r"\b(0x[0-9A-Fa-f]+|\d+)[uU]\b", r"\1", expr)
        expr = re.sub(r"\b[A-Za-z_]\w*\b", lambda t: str(values[t[0]]) if t[0] in values else t[0], expr)
        if not re.fullmatch(r"[0-9a-fA-Fx|&<>()\s]+", expr):
            continue
        values[name] = eval(expr, {"__builtins__": {}})  # digits and | & << >> ( ) only
    return values


def gen_keycodes_ts():
    values = keycode_constants()
    o = [f"// Generated by protocol/gen/gen.py from firmware/core/include/kb/keycodes.h. Do not edit.", ""]
    o += ["/** Every numeric constant in keycodes.h: keycodes, ranges, modifier bits, layer ops. */"]
    o += ["export const KEYCODE_CONSTANTS: Readonly<Record<string, number>> = {"]
    o += [f"  {k}: 0x{v:04x}," for k, v in values.items()]
    o += ["};", ""]
    return "\n".join(o)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if a generated file is out of date")
    args = ap.parse_args()

    spec, messages = load()
    outputs = {
        OUT_H: gen_h(spec, messages),
        OUT_C: gen_c(spec, messages),
        OUT_TS: gen_ts(spec, messages),
        OUT_KC_TS: gen_keycodes_ts(),
    }

    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
        if current != text:
            stale.append(path)
            if not args.check:
                path.write_text(text, encoding="utf-8", newline="\n")

    if args.check and stale:
        for path in stale:
            print(f"out of date: {path.relative_to(REPO)}", file=sys.stderr)
        print("run: python protocol/gen/gen.py", file=sys.stderr)
        return 1
    for path in stale:
        print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
